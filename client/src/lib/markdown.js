/**
 * Markdown Generator for EchoMind
 * Converts structured project memory into clean, shareable Markdown documentation.
 */

export function generateProjectMarkdown(project, memoryData) {
  const data = memoryData || project?.latestSnapshot;
  if (!data) return '# No context available to export.';

  const title = project?.title || 'Project Memory Summary';
  const statusLabels = {
    not_started: '⚪ Not Started',
    in_progress: '🟡 In Progress',
    blocked: '🔴 Blocked',
    completed: '🟢 Completed'
  };

  const statusText = statusLabels[data.status] || data.status || 'In Progress';
  const dateStr = new Date().toLocaleDateString('en-US', {
    weekday: 'short',
    year: 'numeric',
    month: 'short',
    day: 'numeric',
    hour: '2-digit',
    minute: '2-digit'
  });

  let md = `# ${title}\n`;
  md += `**Status:** ${statusText} | **Generated by EchoMind:** ${dateStr}\n\n`;

  // Summary
  md += `## 📋 Project Summary\n${data.project_summary || 'Not specified'}\n\n`;

  // Next Actions (Prioritized)
  md += `## 🎯 Recommended Next Actions\n`;
  if (data.next_actions && data.next_actions.length > 0) {
    data.next_actions.forEach((action, idx) => {
      const priorityBadge = (action.priority || 'medium').toUpperCase();
      md += `${idx + 1}. **[${priorityBadge}]** ${action.task}\n`;
      if (action.reason && action.reason !== 'Not specified') {
        md += `   *Rationale:* ${action.reason}\n`;
      }
    });
  } else {
    md += `*No pending actions identified.*\n`;
  }
  md += `\n`;

  // Completed Work
  md += `## ✅ Completed Work\n`;
  if (data.completed && data.completed.length > 0) {
    data.completed.forEach(item => {
      md += `- [x] ${item}\n`;
    });
  } else {
    md += `*No items marked as completed.*\n`;
  }
  md += `\n`;

  // Pending Tasks
  md += `## ⏳ Pending Tasks\n`;
  if (data.pending && data.pending.length > 0) {
    data.pending.forEach(item => {
      md += `- [ ] ${item}\n`;
    });
  } else {
    md += `*No remaining tasks reported.*\n`;
  }
  md += `\n`;

  // Blockers
  if (data.blockers && data.blockers.length > 0) {
    md += `## 🚨 Known Blockers\n`;
    data.blockers.forEach(blocker => {
      md += `- ⚠️ **${blocker}**\n`;
    });
    md += `\n`;
  }

  // Key Decisions
  if (data.decisions && data.decisions.length > 0) {
    md += `## 💡 Key Decisions\n`;
    data.decisions.forEach(d => {
      md += `- **${d.decision}**\n`;
      if (d.reason && d.reason !== 'Not specified') {
        md += `  *Reason:* ${d.reason}\n`;
      }
    });
    md += `\n`;
  }

  // Risks & Unknowns
  if (data.risks_and_unknowns && data.risks_and_unknowns.length > 0) {
    md += `## 🔍 Risks & Unknowns\n`;
    data.risks_and_unknowns.forEach(risk => {
      md += `- ❓ ${risk}\n`;
    });
    md += `\n`;
  }

  // Assumptions
  if (data.assumptions && data.assumptions.length > 0) {
    md += `## 📌 Cautious Assumptions\n`;
    data.assumptions.forEach(assump => {
      md += `- ${assump}\n`;
    });
    md += `\n`;
  }

  md += `---\n*Generated by EchoMind — AI-powered Project Memory & Context Recovery Engine*`;

  return md;
}
